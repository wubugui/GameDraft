"""物件标签受控词表（`ItemDef.tags`）。

**单一真相源**：物品编辑器的勾选框与校验器的拼写收敛都读这一份，不各存一份
（norms 不变量 8：宁可消灭镜像，也不维护两份手工清单）。

标签是**给系统看的分类，不是玩家可见文案**——用途是让"用点"（检视热区的用物表、
遭遇选项等）按类别接受物件，而不必逐个点名物件 id。收敛拼写是这件事成立的前提：
一旦"辟邪 / 驱邪 / 避邪"三个同义词并存，按类别匹配当场失效，而且**不会报错**，
只会安静地少匹配一批物件。

要加新标签就在这里加一行。词表外的值在数据里是**保值不拦**的：编辑器原样展示并
写回（共享控件保值契约），校验器只出 warning——避免"改个代码才能存内容"。
"""

from __future__ import annotations

#: 受控词表；顺序即编辑器里勾选框的排布顺序。
ITEM_TAGS: tuple[str, ...] = (
    "辟邪",
    "沾秽",
    "食物",
    "引火",
    "信物",
)


def is_known_item_tag(tag: str) -> bool:
    return str(tag).strip() in ITEM_TAGS
