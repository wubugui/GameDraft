/**
 * `Renderer.uiLayer` 的**层序表**：这一层里谁压谁，全项目只此一份。
 *
 * **为什么住在渲染层而不是 `ui/UITheme`**：`uiLayer` 归 `Renderer`，可它的子节点来自两侧
 * ——UI 层（面板 / 世界浮标 / toast / 说明卡）与**系统层**（切场遮幕、持久黑幕）。表若留在
 * `src/ui/` 下，系统层要用就得反向 import UI（违反分层律：依赖只能自上而下）。
 * `UITheme.z` 原样转出这张表，UI 侧照旧写 `UITheme.z.panel`，改动只发生在这里。
 *
 * **写了就生效，不需要手动开 `sortableChildren`**：Pixi v8 的 zIndex setter 会走
 * `sortMixin.depthOfChildModified()`，自动把父容器的 `sortableChildren` 置 true
 * （`node_modules/pixi.js/lib/scene/container/container-mixins/sortMixin.mjs`）。
 * 排序稳定：**没设 zIndex 的元素都是 0，彼此之间仍按添加顺序叠放**，只有显式设了值的整体上浮。
 *
 * 带（从下往上）：
 *
 * - **0 带（不在本表里，故意的）**：HUD、对话框、遭遇、选项、查看框、长按提示、
 *   过场的淡黑 / 闪白 / 字幕框、dev 徽标、调试线。这一带内部的次序**全靠插入序**
 *   （过场字幕压在过场淡黑之上就是这么来的）——别给它们发 z，一个人写了就把整带的约定拆了。
 * - **worldMarker(5)**：任务引导的浮标 / 出屏箭头 / 进场提示条。它是贴在世界上的标记：
 *   压过 HUD（箭头贴边时不该被 HUD 吃掉），但**必须被任何弹出面板压住**。
 * - **panel(10)**：`UIWindow` 窗体（行囊 / 规矩本 / 活计 / 地图 / 铺子 / 暂停菜单各页 …）。
 *   2026-09-23 之前面板一律留在 0 带，"面板盖住浮标"只靠"面板挂得晚"这条插入序，而浮标
 *   的 5 恒压在它们之上——暂停菜单存档页 / 设置页上挂着一枚菱形浮标与"打更的 235"就是这个。
 * - **curtain(20)**：切场遮幕与持久黑幕（`SceneManager`）。必须压过面板：暂停菜单点「读档」
 *   是**读完才关菜单**的，标题页「继续」同理，遮幕盖不住菜单就等于把加载画面藏在菜单后面。
 * - **toast(50) / banner(51)**：流水播报与任务横幅，恒在面板之上（连 toast 之后才打开的
 *   面板也压不住它们，这正是要的）。
 * - **tooltip(60)**：确认框 / 文字输入框 / 说明卡。它们多半是**从面板里弹出来的**，必须更高。
 * - **debug(100)**：调试浮层。
 *
 * ⚠ 加新值之前先想清楚它该压过谁**以及它会不会把 0 带的插入序约定顶掉**。
 */
export const UI_LAYER_Z = {
  /** 任务引导浮标：HUD 之上、面板之下 */
  worldMarker: 5,
  /** `UIWindow` 窗体 */
  panel: 10,
  /** 切场遮幕 / 持久黑幕：连面板一起盖住 */
  curtain: 20,
  toast: 50,
  /** 任务横幅：与 toast 同带不同车道，但真撞上时大事（新任务）压过流水播报 */
  banner: 51,
  tooltip: 60,
  debug: 100,
} as const;
